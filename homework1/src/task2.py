# Integers
def integer_mult(int1, int2):
    return int1 * int2

# Floating-Point Numbers
def float_division(float1, float2):
    return float1/float2

# String
def string_invert(str):
    string_reversed = str[::-1]
    return string_reversed

# Boolean
def is_capitalized(str):
    return str.isupper()
